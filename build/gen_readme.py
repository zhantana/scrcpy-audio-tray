# -*- coding: utf-8 -*-
import os

base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # 仓库根目录

readme = """手机音频托盘  v1.3
============================================================

把手机的声音无线传到电脑耳机，同时可以把手机画面投到电脑上。


一、首次使用
------------------------------------------------------------
有线（最稳，延迟最低）
1. 手机「设置 → 开发者选项」里打开「USB 调试」
2. 数据线插到电脑，手机上点「允许 USB 调试」
3. 双击桌面的「手机音频托盘」启动

无线
1. 手机「设置 → 开发者选项 → 无线调试」，打开开关
2. 双击「无线-首次配对.bat」，按提示输入手机上显示的配对码
3. 双击桌面的「手机音频托盘」启动

两种都插着时优先走有线；插上/拔掉数据线会自动切换。


二、投屏窗口
------------------------------------------------------------
投屏时会开一个窗口，顶部只有一行：
标题、 操作 、 最小化 关闭

「操作」点开就是全部功能：

  设备    切换设备、重命名、唤醒并解锁、重新连接
  音频    启动转发、停止、暂停·继续（手机）、缓冲、音频格式
  视图    窗口置顶、帧率、显示手机画面、全屏（F11）
  帮助    快捷键说明、查看日志、打开使用说明
  关于    版本号

* 按住这行空白处可以拖动窗口
* 拖窗口四边可以改大小，画面跟着缩，不会变形
* 双击这行可以最大化，再双击还原
* 拖到屏幕边上会自动分屏
* 窗口没有底部状态条，画面直接到底

点右上角的关闭按钮 = 停止投屏，右下角的托盘图标还在。
双击托盘图标可以把窗口再叫出来。


三、托盘菜单（右键点右下角图标）
------------------------------------------------------------
  启动 / 停止              手动开关
  显示手机画面（投屏）      勾上就是投屏模式，不勾只听声音
  投屏窗口置顶              勾上后窗口压在其他窗口之上，点了立刻生效
  投屏帧数                  30 / 60 / 90 / 120 / 144 / 不限，默认 60
  暂停 / 继续（手机）       把手机上的视频、音乐暂停或继续，默认 Ctrl+Alt+P
  投屏开 / 关                一键开关画面，声音不断，默认 F7
  快捷键                    暂停键、投屏键各自 修改 / 禁用 / 恢复默认
  唤醒并解锁                手机锁着时点它
  缓冲 / 延迟               音频缓冲，越低越跟手
  音频格式                  无损 PCM（默认）/ Opus（省带宽）
  选择设备                  按 USB 有线 / WiFi 无线 分组，每台标注连接方式
  重命名设备                多台手机时用
  忘记解锁密码              手机改了密码后用

窗口菜单和托盘菜单是同一套功能，在哪边点都一样。


四、常见情况
------------------------------------------------------------
* 只看画面不要声音：不支持，声音和画面同一条通道
* 只要声音不要画面：取消勾选「显示手机画面」，这时不会开窗口
* 投屏时手机黑屏：正常。画面照样在电脑上，手机黑屏是省电防烧屏
* 画面卡：把「投屏帧数」改成 60 或 30
* 手机睡了画面停住：窗口里会变黑并显示「手机已息屏」，
  点中间的「唤醒并解锁」按钮即可恢复
* 快捷键按了手机没反应：只有视频、音乐这类播放器认这个键。
  游戏不响应媒体键，也听不到「手机上没在播放」的提示就说明没有可暂停的媒体
* 快捷键和别的软件冲突：右键托盘 → 快捷键 → 对应键 → 修改，换一个
* 两个快捷键不能设成同一个键，设重复时后一个会被清空并提示
* 万一窗口里没有画面、桌面另外冒出一个 scrcpy 窗口：
  说明这台机器没法把画面装进窗口，会自动退回原来的方式，
  声音和操作都不受影响，只是没有菜单栏


五、文件说明
------------------------------------------------------------
scrcpy-audio-tray.ps1              主程序（窗口 + 托盘）
scrcpy\\                            投屏引擎（已内置，不用另装）
启动-手机音频托盘.vbs              静默启动，无黑色命令行窗口
无线-首次配对.bat                  第一次连手机时用
手机投屏带声音.bat                 单独再开一路投屏（带声音）
无线音频-游戏模式.bat              纯音频，低延迟
手机声音到电脑-低延迟游戏模式.bat   纯音频（有线无线都行）
README.txt                         本文件


六、配置文件（首次运行后生成）
------------------------------------------------------------
settings.json      缓冲、编码、帧率、置顶、投屏开关、记住的无线地址、快捷键
device-pin.json    自动解锁用的锁屏密码，明文存在本机，可自行删除
wifi_target.txt    旧版留下的无线地址，会自动搬进 settings.json


七、卸载
------------------------------------------------------------
控制面板 → 应用 → 手机音频托盘 → 卸载
注意：卸载会把上面三个配置文件一起删掉。


八、已知限制
------------------------------------------------------------
1. 同一台手机同一时刻只能被一个程序抓声音。同时开两路投屏时，
   后开的那一路出声；关掉它之后托盘会自动接回来（画面会闪一下）
2. 数字密码可以自动解锁；图案锁、指纹、人脸解锁无法自动完成
3. 无线方式需要 Android 11 及以上（无线调试从 11 开始提供）
4. 无线方式手机和电脑要连同一个 Wi-Fi
5. 不支持蓝牙：adb 只有 USB 和网络两种通道，走不了蓝牙，
   菜单里的「蓝牙（不可用）」只是说明，点了没反应是正常的


九、兼容性
------------------------------------------------------------
Windows 10 / 11 64 位
手机：Android 11 及以上
"""

p = os.path.join(base, "README.txt")
open(p, "wb").write(readme.replace("\n", "\r\n").encode("gbk"))
print("OK", p, os.path.getsize(p), "bytes")
